"""
Pseudo-Label Dataset for Depth Anything V2 Training.

This module provides dataset classes for loading images and their corresponding
pseudo-labels generated by the teacher model.
"""

import torch
from torch.utils.data import Dataset, DataLoader
from PIL import Image
import numpy as np
import os
from pathlib import Path
from typing import Optional, List, Tuple, Dict, Any, Callable, Union
import json


class DA2PseudoLabelDataset(Dataset):
    """
    Dataset for loading images and pseudo-labels for training.
    
    Supports both precomputed pseudo-labels (loaded from disk) and 
    on-the-fly generation using a teacher model.
    """
    
    def __init__(
        self,
        image_dir: str,
        pseudo_label_dir: Optional[str] = None,
        teacher_model: Optional[Any] = None,
        precompute: bool = True,
        image_extensions: List[str] = None,
        transform: Optional[Callable] = None,
        target_resolution: Tuple[int, int] = (518, 518),
        normalize_depth: bool = True,
        confidence_threshold: float = 0.0,
    ):
        """
        Initialize the dataset.
        
        Args:
            image_dir: Directory containing input images
            pseudo_label_dir: Directory containing precomputed pseudo-labels (optional)
            teacher_model: Teacher model for on-the-fly pseudo-label generation
            precompute: Whether to use precomputed labels or generate on-the-fly
            image_extensions: List of valid image extensions
            transform: Optional transform to apply to images
            target_resolution: Target resolution for images and depth maps
            normalize_depth: Whether to normalize depth values to [0, 1]
            confidence_threshold: Minimum confidence for including samples
        """
        self.image_dir = Path(image_dir)
        self.pseudo_label_dir = Path(pseudo_label_dir) if pseudo_label_dir else None
        self.teacher_model = teacher_model
        self.precompute = precompute
        self.image_extensions = image_extensions or [".jpg", ".jpeg", ".png", ".bmp", ".webp"]
        self.transform = transform
        self.target_resolution = target_resolution
        self.normalize_depth = normalize_depth
        self.confidence_threshold = confidence_threshold
        
        # Collect image paths
        self.image_paths = self._collect_image_paths()
        
        # Verify pseudo-labels exist if using precomputed mode
        if self.precompute and self.pseudo_label_dir is not None:
            self._verify_pseudo_labels()
        
        print(f"Found {len(self.image_paths)} images in {image_dir}")
    
    def _collect_image_paths(self) -> List[Path]:
        """Collect all valid image paths from the directory."""
        image_paths = []
        
        for ext in self.image_extensions:
            image_paths.extend(self.image_dir.glob(f"**/*{ext}"))
            image_paths.extend(self.image_dir.glob(f"**/*{ext.upper()}"))
        
        return sorted(list(set(image_paths)))
    
    def _verify_pseudo_labels(self) -> None:
        """Verify that pseudo-labels exist for all images."""
        missing = []
        
        for img_path in self.image_paths:
            label_path = self.pseudo_label_dir / f"{img_path.stem}_depth.npy"
            if not label_path.exists():
                missing.append(img_path.name)
        
        if missing:
            print(f"Warning: {len(missing)} pseudo-labels missing. These samples will be skipped.")
            self.image_paths = [
                p for p in self.image_paths 
                if (self.pseudo_label_dir / f"{p.stem}_depth.npy").exists()
            ]
    
    def __len__(self) -> int:
        return len(self.image_paths)
    
    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        """
        Get a sample from the dataset.
        
        Returns:
            Dictionary containing:
                - 'image': Input image tensor
                - 'depth': Pseudo-label depth map
                - 'confidence': Confidence map (if available)
                - 'image_path': Path to the original image
        """
        img_path = self.image_paths[idx]
        
        # Load image
        image = Image.open(img_path).convert('RGB')
        
        # Apply transforms
        if self.transform:
            image = self.transform(image)
        else:
            # Default transform: resize and normalize
            image = image.resize(self.target_resolution, Image.BILINEAR)
            image = torch.from_numpy(np.array(image)).permute(2, 0, 1).float() / 255.0
            
            # Normalize with ImageNet stats
            mean = torch.tensor([0.485, 0.456, 0.406]).view(3, 1, 1)
            std = torch.tensor([0.229, 0.224, 0.225]).view(3, 1, 1)
            image = (image - mean) / std
        
        # Load or generate pseudo-label
        if self.precompute and self.pseudo_label_dir is not None:
            depth, confidence = self._load_pseudo_label(img_path)
        elif self.teacher_model is not None:
            depth, confidence = self._generate_pseudo_label(image)
        else:
            raise ValueError("No pseudo-label source available. Provide either pseudo_label_dir or teacher_model.")
        
        # Apply confidence threshold
        if confidence is not None and self.confidence_threshold > 0:
            valid_mask = confidence >= self.confidence_threshold
            if valid_mask.sum() == 0:
                # Skip this sample if no valid pixels
                return self.__getitem__((idx + 1) % len(self))
        
        return {
            'image': image,
            'depth': depth,
            'confidence': confidence if confidence is not None else torch.ones_like(depth),
            'image_path': str(img_path),
        }
    
    def _load_pseudo_label(self, image_path: Path) -> Tuple[torch.Tensor, Optional[torch.Tensor]]:
        """Load precomputed pseudo-label from disk."""
        depth_path = self.pseudo_label_dir / f"{image_path.stem}_depth.npy"
        conf_path = self.pseudo_label_dir / f"{image_path.stem}_confidence.npy"
        
        # Load depth
        depth = np.load(depth_path)
        depth = torch.from_numpy(depth).float()
        
        # Normalize if needed
        if self.normalize_depth:
            depth_min = depth.min()
            depth_max = depth.max()
            depth = (depth - depth_min) / (depth_max - depth_min + 1e-8)
        
        # Load confidence if exists
        confidence = None
        if conf_path.exists():
            confidence = np.load(conf_path)
            confidence = torch.from_numpy(confidence).float()
        
        return depth, confidence
    
    def _generate_pseudo_label(
        self, 
        image: Union[torch.Tensor, Image.Image]
    ) -> Tuple[torch.Tensor, Optional[torch.Tensor]]:
        """Generate pseudo-label using teacher model."""
        if self.teacher_model is None:
            raise ValueError("Teacher model not provided.")
        
        result = self.teacher_model.predict(image, return_confidence=True)
        
        depth = result['depth'].squeeze(0)
        confidence = result.get('confidence', None)
        if confidence is not None:
            confidence = confidence.squeeze(0)
        
        return depth, confidence
    
    def collate_fn(self, batch: List[Dict]) -> Dict[str, torch.Tensor]:
        """Custom collate function for batching."""
        images = torch.stack([item['image'] for item in batch])
        depths = torch.stack([item['depth'] for item in batch])
        confidences = torch.stack([item['confidence'] for item in batch])
        image_paths = [item['image_path'] for item in batch]
        
        return {
            'images': images,
            'depths': depths,
            'confidences': confidences,
            'image_paths': image_paths,
        }


def create_dataloader(
    dataset: DA2PseudoLabelDataset,
    batch_size: int = 8,
    num_workers: int = 4,
    shuffle: bool = True,
    pin_memory: bool = True,
) -> DataLoader:
    """
    Create a DataLoader for the pseudo-label dataset.
    
    Args:
        dataset: The dataset to load
        batch_size: Batch size
        num_workers: Number of worker processes
        shuffle: Whether to shuffle data
        pin_memory: Whether to pin memory for faster GPU transfer
        
    Returns:
        PyTorch DataLoader
    """
    return DataLoader(
        dataset,
        batch_size=batch_size,
        num_workers=num_workers,
        shuffle=shuffle,
        pin_memory=pin_memory,
        collate_fn=dataset.collate_fn,
    )


def precompute_all_pseudo_labels(
    teacher_model: Any,
    image_dir: str,
    output_dir: str,
    batch_size: int = 8,
    image_extensions: List[str] = None,
    save_format: str = "npy",
) -> None:
    """
    Precompute pseudo-labels for all images in a directory.
    
    Args:
        teacher_model: Teacher model for generating pseudo-labels
        image_dir: Directory containing input images
        output_dir: Directory to save pseudo-labels
        batch_size: Batch size for inference
        image_extensions: Valid image extensions
        save_format: Format to save pseudo-labels
    """
    from tqdm import tqdm
    
    # Create dataset without pseudo-labels
    dataset = DA2PseudoLabelDataset(
        image_dir=image_dir,
        pseudo_label_dir=None,
        teacher_model=teacher_model,
        precompute=False,
        image_extensions=image_extensions,
    )
    
    # Create dataloader
    dataloader = create_dataloader(
        dataset,
        batch_size=batch_size,
        num_workers=4,
        shuffle=False,
    )
    
    os.makedirs(output_dir, exist_ok=True)
    
    print(f"Precomputing pseudo-labels for {len(dataset)} images...")
    
    for batch in tqdm(dataloader, desc="Generating pseudo-labels"):
        image_paths = batch['image_paths']
        
        # Generate predictions
        results = teacher_model.predict_batch(
            batch['images'],
            return_confidence=True,
            batch_size=batch_size,
        )
        
        depths = results['depth']
        confidences = results.get('confidence', None)
        
        # Save each prediction
        for i, img_path in enumerate(image_paths):
            depth = depths[i]
            confidence = confidences[i] if confidences is not None else None
            
            teacher_model.save_pseudo_label(
                image_path=img_path,
                output_dir=output_dir,
                depth=depth,
                confidence=confidence,
                save_format=save_format,
            )
    
    print(f"Pseudo-labels saved to {output_dir}")
